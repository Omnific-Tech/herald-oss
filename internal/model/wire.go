package model

import (
	"encoding/json"
	"strings"
	"time"
)

// MaxPushDeliveryBytes leaves room for Web Push encryption and FCM framing
// inside their 4096-byte transport limits.
const MaxPushDeliveryBytes = 3500

// PublishRequest is the version 1 publish envelope sent to POST /v1/messages.
// It carries no application field; see store.Producers.
type PublishRequest struct {
	// IdempotencyKey is unique per application. Replaying one returns the
	// original message and creates no additional deliveries.
	IdempotencyKey string `json:"idempotency_key" binding:"required,max=200"`
	// Channel is the Android notification channel and the coarse routing key.
	Channel string `json:"channel" binding:"required,max=64"`
	// Topic is the fine routing key, for example "earthquake.jakarta".
	Topic    string   `json:"topic" binding:"max=200"`
	Priority Priority `json:"priority" binding:"omitempty,oneof=normal high"`
	Title    string   `json:"title" binding:"required,max=200"`
	Body     string   `json:"body" binding:"required,max=2000"`
	// Link is a path on the application's own trusted origin. It must start with
	// a single "/" and is rejected otherwise, including the protocol-relative
	// "//host" and "/\host" forms that browsers resolve to another origin.
	Link string `json:"link" binding:"omitempty,herald_path,max=500"`
	// Data is opaque product payload passed through to the client unchanged.
	Data json.RawMessage `json:"data"`
	// CollapseKey lets a newer message supersede an undelivered older one.
	CollapseKey string `json:"collapse_key" binding:"max=200"`
	// ExpiresAt bounds how long the message may still be displayed.
	ExpiresAt time.Time `json:"expires_at" binding:"required"`
}

// PublishResponse is returned for both new and replayed publications.
type PublishResponse struct {
	MessageID string `json:"message_id"`
	// Deduplicated is true when IdempotencyKey matched an existing message.
	Deduplicated bool `json:"deduplicated"`
	// DeviceCount is how many devices the message fanned out to.
	DeviceCount int `json:"device_count"`
}

// RegisterDeviceRequest is sent to POST /v1/devices/register.
//
// With no Authorization header it creates a device. With a device's own token
// it rotates that device's credential, keeping its sequence and history. There
// is no caller-supplied device identifier in either case, so no caller can name
// a device belonging to someone else.
type RegisterDeviceRequest struct {
	// Application is the target application slug, required only when creating.
	Application string   `json:"application" binding:"omitempty,max=64"`
	Platform    Platform `json:"platform" binding:"required,oneof=android web"`
	DisplayName string   `json:"display_name" binding:"max=200"`
	// FCMFID is the Firebase Installation ID used to address an Android app.
	FCMFID string `json:"fcm_fid" binding:"max=200"`
	// WebPush is required when Platform is web and ignored otherwise.
	WebPush *WebPushSubscription `json:"webpush"`
}

// RegisterDeviceResponse carries the bearer token used for the stream and acks.
// DeviceToken is returned only here and is stored hashed.
type RegisterDeviceResponse struct {
	DeviceID string `json:"device_id"`
	// InstallID is generated by Herald and is stable across token rotations.
	InstallID   string `json:"install_id"`
	DeviceToken string `json:"device_token"`
	// AcknowledgedSequence is the correct value to pass as after_sequence. It is
	// the last sequence this device acknowledged, not the last one allocated to
	// it: resuming from the latter would skip everything received but unacked.
	AcknowledgedSequence int64 `json:"acknowledged_sequence"`
}

// UpdateSubscriptionsRequest replaces the full subscription set for the calling
// device. Sending an empty list unsubscribes the device from everything.
type UpdateSubscriptionsRequest struct {
	Subscriptions []Subscription `json:"subscriptions" binding:"dive"`
}

// UpdateFCMRequest refreshes the calling Android device's Firebase installation.
type UpdateFCMRequest struct {
	FCMFID string `json:"fcm_fid" binding:"required,max=200"`
}

// StreamEvent is the delivery envelope carried by FCM and Web Push.
type StreamEvent struct {
	DeliveryID string          `json:"delivery_id"`
	Sequence   int64           `json:"sequence"`
	Message    DeliveryMessage `json:"message"`
}

// DeliveryMessage is the part of a message a device receives. Producer,
// application, and idempotency identifiers stay server-side.
type DeliveryMessage struct {
	ID          string          `json:"id"`
	Channel     string          `json:"channel"`
	Topic       string          `json:"topic,omitempty"`
	Priority    Priority        `json:"priority"`
	Title       string          `json:"title"`
	Body        string          `json:"body"`
	Link        string          `json:"link,omitempty"`
	Data        json.RawMessage `json:"data,omitempty"`
	CollapseKey string          `json:"collapse_key,omitempty"`
	ExpiresAt   time.Time       `json:"expires_at"`
	CreatedAt   time.Time       `json:"created_at"`
}

// Delivery returns the device-facing view of m.
func (m Message) Delivery() DeliveryMessage {
	return DeliveryMessage{
		ID: m.ID, Channel: m.Channel, Topic: m.Topic, Priority: m.Priority,
		Title: m.Title, Body: m.Body, Link: m.Link, Data: m.Data,
		CollapseKey: m.CollapseKey, ExpiresAt: m.ExpiresAt, CreatedAt: m.CreatedAt,
	}
}

// AckRequest is sent to POST /v1/deliveries/:delivery_id/ack. Acks are
// idempotent; repeating one returns 200 with the stored acknowledgement.
type AckRequest struct {
	Status AckStatus `json:"status" binding:"required,oneof=delivered displayed suppressed"`
}

// VAPIDPublicKeyResponse is returned by the public per-application VAPID
// endpoint that a PWA calls before pushManager.subscribe().
type VAPIDPublicKeyResponse struct {
	Application string `json:"application"`
	// PublicKey is the base64url-encoded P-256 application server key.
	PublicKey string `json:"public_key"`
}

// ErrorResponse is the uniform error body for every non-2xx response.
type ErrorResponse struct {
	Error string `json:"error"`
}

// PushDeliverySize estimates the final client envelope using fixed-width IDs.
func PushDeliverySize(request PublishRequest) (int, error) {
	data := request.Data
	if len(data) == 0 {
		data = json.RawMessage(`{}`)
	}
	fixedID := strings.Repeat("0", 36)
	payload, err := json.Marshal(StreamEvent{
		DeliveryID: fixedID,
		Sequence:   9_223_372_036_854_775_807,
		Message: DeliveryMessage{
			ID: fixedID, Channel: request.Channel,
			Topic: request.Topic, Priority: request.Priority, Title: request.Title,
			Body: request.Body, Link: request.Link, Data: data,
			CollapseKey: request.CollapseKey, ExpiresAt: request.ExpiresAt,
			CreatedAt: time.Now().UTC(),
		},
	})
	return len(payload), err
}
