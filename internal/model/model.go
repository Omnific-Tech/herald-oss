// Package model defines the version 1 Herald wire and storage types.
//
// Compatibility rules for these types are in docs/versioning.md.
package model

import (
	"encoding/json"
	"time"
)

// Platform identifies the delivery transport a device uses.
type Platform string

const (
	// PlatformAndroid receives deliveries over the authenticated SSE stream.
	PlatformAndroid Platform = "android"
	// PlatformWeb receives deliveries over Web Push (VAPID).
	PlatformWeb Platform = "web"
)

// Priority controls how aggressively a delivery is surfaced on the device.
type Priority string

const (
	PriorityNormal Priority = "normal"
	PriorityHigh   Priority = "high"
)

// AckStatus is the client-reported outcome carried on an acknowledgement.
type AckStatus string

const (
	// AckDelivered means the client durably received the delivery.
	AckDelivered AckStatus = "delivered"
	// AckDisplayed means the client rendered a notification for it.
	AckDisplayed AckStatus = "displayed"
	// AckSuppressed means the client received it but did not display it, for
	// example because the message had already expired on arrival.
	AckSuppressed AckStatus = "suppressed"
)

// Application is a product that owns producers, devices, and a VAPID keypair.
type Application struct {
	ID          string    `json:"id"`
	Slug        string    `json:"slug"`
	DisplayName string    `json:"display_name"`
	Origin      string    `json:"origin"`
	CreatedAt   time.Time `json:"created_at"`
}

// Producer is an authenticated publisher bound to exactly one application.
type Producer struct {
	ID            string     `json:"id"`
	ApplicationID string     `json:"application_id"`
	Name          string     `json:"name"`
	RevokedAt     *time.Time `json:"revoked_at,omitempty"`
	CreatedAt     time.Time  `json:"created_at"`
}

// Device is one installed client of one application. InstallID is generated by
// Herald and is stable across token rotations.
type Device struct {
	ID            string    `json:"id"`
	ApplicationID string    `json:"application_id"`
	Platform      Platform  `json:"platform"`
	InstallID     string    `json:"install_id"`
	DisplayName   string    `json:"display_name,omitempty"`
	LastSequence  int64     `json:"last_sequence"`
	CreatedAt     time.Time `json:"created_at"`
}

// WebPushSubscription is the browser PushSubscription for a web platform device.
type WebPushSubscription struct {
	Endpoint string `json:"endpoint"`
	P256DH   string `json:"p256dh"`
	Auth     string `json:"auth"`
}

// Subscription is one (channel, topic) routing entry for a device. An empty
// Topic subscribes the device to every message on the channel.
type Subscription struct {
	Channel string `json:"channel"`
	Topic   string `json:"topic,omitempty"`
}

// Message is a stored publication.
type Message struct {
	ID             string          `json:"id"`
	ApplicationID  string          `json:"application_id"`
	ProducerID     string          `json:"producer_id,omitempty"`
	AdminUsername  string          `json:"-"`
	IdempotencyKey string          `json:"idempotency_key"`
	Channel        string          `json:"channel"`
	Topic          string          `json:"topic,omitempty"`
	Priority       Priority        `json:"priority"`
	Title          string          `json:"title"`
	Body           string          `json:"body"`
	Link           string          `json:"link,omitempty"`
	Data           json.RawMessage `json:"data,omitempty"`
	CollapseKey    string          `json:"collapse_key,omitempty"`
	// DeviceCount is the fan-out size recorded at publish. It is reported to the
	// producer, never to a device: how many devices a product has is not the
	// recipient's business.
	DeviceCount int       `json:"-"`
	ExpiresAt   time.Time `json:"expires_at"`
	CreatedAt   time.Time `json:"created_at"`
}

// Acknowledgement is the client's confirmation for a delivery. At most one row
// exists per delivery; repeating an ack is a no-op, not an error.
type Acknowledgement struct {
	DeliveryID     string    `json:"delivery_id"`
	Status         AckStatus `json:"status"`
	AcknowledgedAt time.Time `json:"acknowledged_at"`
}
