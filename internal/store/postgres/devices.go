package postgres

import (
	"context"
	"database/sql"
	"errors"
	"fmt"

	"github.com/Omnific-Tech/herald/internal/crypto"
	"github.com/Omnific-Tech/herald/internal/model"
	"github.com/Omnific-Tech/herald/internal/store"
)

type devices struct {
	store *Store
}

const deviceColumns = `id, application_id, platform, install_id, display_name, last_sequence, created_at`

func deviceFields(device *model.Device) []any {
	return []any{
		&device.ID,
		&device.ApplicationID,
		&device.Platform,
		&device.InstallID,
		&device.DisplayName,
		&device.LastSequence,
		&device.CreatedAt,
	}
}

func webPushColumns(subscription *model.WebPushSubscription) (endpoint, p256dh, auth *string) {
	if subscription == nil {
		return nil, nil, nil
	}
	return &subscription.Endpoint, &subscription.P256DH, &subscription.Auth
}

// Create provisions a new device. install_id is generated by the database, so
// it is never a value a caller can choose and therefore never a value another
// caller can guess to have a token minted for someone else's device.
func (d *devices) Create(ctx context.Context, applicationID string, request model.RegisterDeviceRequest) (model.Device, string, error) {
	token, err := crypto.NewToken()
	if err != nil {
		return model.Device{}, "", err
	}

	endpoint, p256dh, auth := webPushColumns(request.WebPush)

	const query = `
		INSERT INTO devices (
			application_id, platform, display_name, token_hash,
			webpush_endpoint, webpush_p256dh, webpush_auth, fcm_fid
		)
		VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
		RETURNING ` + deviceColumns

	var device model.Device
	err = d.store.db.QueryRowContext(ctx, query,
		applicationID, request.Platform, request.DisplayName,
		crypto.HashToken(token), endpoint, p256dh, auth, nullable(request.FCMFID),
	).Scan(deviceFields(&device)...)
	if err != nil {
		return model.Device{}, "", fmt.Errorf("insert device: %w", err)
	}

	return device, token, nil
}

// Rotate issues a new token for a device whose current token the caller has
// already presented. last_sequence and every delivery are kept, so a
// reinstalled client resumes instead of replaying its whole history.
func (d *devices) Rotate(ctx context.Context, deviceID string, request model.RegisterDeviceRequest) (model.Device, string, error) {
	token, err := crypto.NewToken()
	if err != nil {
		return model.Device{}, "", err
	}

	endpoint, p256dh, auth := webPushColumns(request.WebPush)

	const query = `
		UPDATE devices SET
			platform            = $2,
			display_name        = $3,
			token_hash          = $4,
			webpush_endpoint    = $5,
			webpush_p256dh      = $6,
			webpush_auth        = $7,
			webpush_disabled_at = NULL,
			fcm_fid             = $8,
			fcm_disabled_at     = NULL,
			updated_at          = now()
		WHERE id = $1
		RETURNING ` + deviceColumns

	var device model.Device
	err = d.store.db.QueryRowContext(ctx, query,
		deviceID, request.Platform, request.DisplayName,
		crypto.HashToken(token), endpoint, p256dh, auth, nullable(request.FCMFID),
	).Scan(deviceFields(&device)...)
	if errors.Is(err, sql.ErrNoRows) {
		return model.Device{}, "", store.ErrNotFound
	}
	if err != nil {
		return model.Device{}, "", fmt.Errorf("update device: %w", err)
	}

	return device, token, nil
}

func (d *devices) ByToken(ctx context.Context, token string) (model.Device, error) {
	const query = `SELECT ` + deviceColumns + ` FROM devices WHERE token_hash = $1`

	var device model.Device
	err := d.store.db.QueryRowContext(ctx, query, crypto.HashToken(token)).Scan(deviceFields(&device)...)
	if errors.Is(err, sql.ErrNoRows) {
		return model.Device{}, store.ErrNotFound
	}
	if err != nil {
		return model.Device{}, fmt.Errorf("select device: %w", err)
	}
	return device, nil
}

// AcknowledgedSequence is what a client may resume from. last_sequence is the
// highest sequence *allocated* to the device and is always ahead of this.
func (d *devices) AcknowledgedSequence(ctx context.Context, deviceID string) (int64, error) {
	const query = `
		SELECT coalesce(max(sequence), 0)
		FROM deliveries
		WHERE device_id = $1 AND state = 'acknowledged'`

	var sequence int64
	if err := d.store.db.QueryRowContext(ctx, query, deviceID).Scan(&sequence); err != nil {
		return 0, fmt.Errorf("select acknowledged sequence: %w", err)
	}
	return sequence, nil
}

// ReplaceSubscriptions swaps the whole set in one transaction so a device is
// never briefly subscribed to nothing.
func (d *devices) ReplaceSubscriptions(ctx context.Context, deviceID string, subscriptions []model.Subscription) error {
	return d.store.inTransaction(ctx, func(tx *sql.Tx) error {
		var applicationID string
		if err := tx.QueryRowContext(ctx, `SELECT application_id FROM devices WHERE id = $1`, deviceID).Scan(&applicationID); err != nil {
			return fmt.Errorf("read device application: %w", err)
		}
		for _, subscription := range subscriptions {
			if err := validRouting(ctx, tx, applicationID, subscription.Channel, subscription.Topic); err != nil {
				return err
			}
		}
		if _, err := tx.ExecContext(ctx, `DELETE FROM subscriptions WHERE device_id = $1`, deviceID); err != nil {
			return fmt.Errorf("clear subscriptions: %w", err)
		}

		const insert = `
			INSERT INTO subscriptions (device_id, channel, topic)
			VALUES ($1, $2, $3)
			ON CONFLICT (device_id, channel, topic) DO NOTHING`

		for _, subscription := range subscriptions {
			if _, err := tx.ExecContext(ctx, insert, deviceID, subscription.Channel, subscription.Topic); err != nil {
				return fmt.Errorf("insert subscription: %w", err)
			}
		}
		return nil
	})
}

func (d *devices) Subscriptions(ctx context.Context, deviceID string) ([]model.Subscription, error) {
	const query = `
		SELECT channel, topic
		FROM subscriptions
		WHERE device_id = $1
		ORDER BY channel, topic`

	rows, err := d.store.db.QueryContext(ctx, query, deviceID)
	if err != nil {
		return nil, fmt.Errorf("select subscriptions: %w", err)
	}
	defer func() { _ = rows.Close() }()

	subscriptions := []model.Subscription{}
	for rows.Next() {
		var subscription model.Subscription
		if err := rows.Scan(&subscription.Channel, &subscription.Topic); err != nil {
			return nil, fmt.Errorf("scan subscription: %w", err)
		}
		subscriptions = append(subscriptions, subscription)
	}
	return subscriptions, rows.Err()
}

func (d *devices) UpdateFCM(ctx context.Context, deviceID, fcmFID string) error {
	const query = `
		UPDATE devices
		SET fcm_fid = $2, fcm_disabled_at = NULL, updated_at = now()
		WHERE id = $1 AND platform = 'android'`
	result, err := d.store.db.ExecContext(ctx, query, deviceID, fcmFID)
	if err != nil {
		return fmt.Errorf("update fcm: %w", err)
	}
	affected, err := result.RowsAffected()
	if err != nil {
		return err
	}
	if affected == 0 {
		return store.ErrNotFound
	}
	return nil
}

// DisableWebPush clears the subscription and leaves everything else intact.
// Deleting the device would cascade away its sequence and its acknowledged
// history, so a later re-subscribe would replay from zero.
func (d *devices) DisableWebPush(ctx context.Context, deviceID string) error {
	const query = `
		UPDATE devices
		SET webpush_disabled_at = now(),
		    webpush_endpoint    = NULL,
		    webpush_p256dh      = NULL,
		    webpush_auth        = NULL,
		    updated_at          = now()
		WHERE id = $1`

	if _, err := d.store.db.ExecContext(ctx, query, deviceID); err != nil {
		return fmt.Errorf("disable web push: %w", err)
	}
	return nil
}

func (d *devices) DisableFCM(ctx context.Context, deviceID string) error {
	const query = `
		UPDATE devices
		SET fcm_disabled_at = now(), fcm_fid = NULL, updated_at = now()
		WHERE id = $1`

	if _, err := d.store.db.ExecContext(ctx, query, deviceID); err != nil {
		return fmt.Errorf("disable fcm: %w", err)
	}
	return nil
}

func nullable(value string) *string {
	if value == "" {
		return nil
	}
	return &value
}

func (d *devices) TouchLastSeen(ctx context.Context, deviceID string) error {
	const query = `UPDATE devices SET last_seen_at = now() WHERE id = $1`
	if _, err := d.store.db.ExecContext(ctx, query, deviceID); err != nil {
		return fmt.Errorf("touch device: %w", err)
	}
	return nil
}
